// Command pinhashes writes the SHA-256 of every release archive and of the
// binary inside it into each language package, so a package trusts a release
// only if it matches what was committed here.
//
//	gh release download v0.3.0 --dir /tmp/release
//	go run ./scripts/pinhashes /tmp/release
//
// With -clear it empties the pins, which a package treats as having no
// release to download. With -fixture it writes one JSON file instead.
package main

import (
	"bufio"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	"github.com/sendscore/sendscore/scripts/internal/release"
)

type pin struct {
	Archive string `json:"archive"`
	Binary  string `json:"binary"`
}

var archiveName = regexp.MustCompile(`^sendscore_(.+)_(\w+_\w+)\.(tar\.gz|zip)$`)

// read checks each archive against checksums.txt and hashes what is inside.
func read(dir string) (map[string]pin, error) {
	f, err := os.Open(filepath.Join(dir, "checksums.txt"))
	if err != nil {
		return nil, err
	}
	defer f.Close()
	pins := map[string]pin{}
	version := ""
	s := bufio.NewScanner(f)
	for s.Scan() {
		parts := strings.Fields(s.Text())
		if len(parts) != 2 {
			continue
		}
		m := archiveName.FindStringSubmatch(parts[1])
		if m == nil {
			return nil, fmt.Errorf("unexpected file in checksums.txt: %s", parts[1])
		}
		if version != "" && m[1] != version {
			return nil, fmt.Errorf("two versions in checksums.txt: %s and %s", version, m[1])
		}
		version = m[1]
		archive, err := os.ReadFile(filepath.Join(dir, parts[1]))
		if err != nil {
			return nil, err
		}
		if release.Sum(archive) != strings.ToLower(parts[0]) {
			return nil, fmt.Errorf("%s does not match checksums.txt", parts[1])
		}
		binary, err := release.Extract(archive, parts[1])
		if err != nil {
			return nil, err
		}
		pins[m[2]] = pin{Archive: strings.ToLower(parts[0]), Binary: release.Sum(binary)}
	}
	if err := s.Err(); err != nil {
		return nil, err
	}
	for _, p := range release.Platforms {
		if _, ok := pins[p]; !ok {
			return nil, fmt.Errorf("checksums.txt has no %s", p)
		}
	}
	return pins, nil
}

const header = "Generated by scripts/pinhashes. Do not edit."

type target struct {
	path  string
	open  string
	line  string // format: platform, archive, binary
	close string
}

var targets = []target{
	{"packages/sdk/src/hashes.ts", "// " + header + "\n\nexport const HASHES: Record<string, { archive: string; binary: string }> = {", "\n  %s: { archive: \"%s\", binary: \"%s\" },", "\n};\n"},
	{"packages/python/src/sendscore/_hashes.py", "# " + header + "\n\nHASHES: dict[str, tuple[str, str]] = {", "\n    \"%s\": (\"%s\", \"%s\"),", "\n}\n"},
	{"packages/php/src/Hashes.php", "<?php\n\ndeclare(strict_types=1);\n\nnamespace SendScore;\n\n/** " + header + " */\nfinal class Hashes\n{\n    /** @var array<string, array{0: string, 1: string}> */\n    public const PINS = [", "\n        '%s' => ['%s', '%s'],", "\n    ];\n}\n"},
	{"packages/rust/src/hashes.rs", "// " + header + "\n\npub(crate) const HASHES: &[(&str, &str, &str)] = &[", "\n    (\"%s\", \"%s\", \"%s\"),", "\n];\n"},
	{"packages/ruby/lib/sendscore/hashes.rb", "# " + header + "\n\nmodule SendScore\n  HASHES = {", "\n    \"%s\" => [\"%s\", \"%s\"],", "\n  }.freeze\nend\n"},
	{"packages/java/src/main/java/ai/sendscore/Hashes.java", "package ai.sendscore;\n\nimport java.util.Map;\n\n/** " + header + " */\nfinal class Hashes {\n  static final Map<String, String[]> PINS = Map.ofEntries(", "\n      Map.entry(\"%s\", new String[] {\"%s\", \"%s\"})", "\n  );\n\n  private Hashes() {}\n}\n"},
	{"packages/dotnet/src/SendScore/Hashes.cs", "namespace SendScore;\n\n/// <summary>" + header + "</summary>\ninternal static class Hashes\n{\n    internal static readonly Dictionary<string, (string Archive, string Binary)> Pins = new()\n    {", "\n        [\"%s\"] = (\"%s\", \"%s\"),", "\n    };\n}\n"},
	{"packages/elixir/lib/sendscore/hashes.ex", "defmodule SendScore.Hashes do\n  @moduledoc false\n  # " + header + "\n\n  def pins do\n    %{", "\n      \"%s\" => {\"%s\", \"%s\"},", "\n    }\n  end\nend\n"},
}

func render(t target, pins map[string]pin) string {
	var b strings.Builder
	b.WriteString(t.open)
	keys := make([]string, 0, len(pins))
	for k := range pins {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for i, k := range keys {
		line := fmt.Sprintf(t.line, k, pins[k].Archive, pins[k].Binary)
		if strings.HasSuffix(t.path, ".java") && i < len(keys)-1 {
			line += ","
		}
		if strings.HasSuffix(t.path, ".ex") && i == len(keys)-1 {
			line = strings.TrimSuffix(line, ",")
		}
		b.WriteString(line)
	}
	b.WriteString(t.close)
	return b.String()
}

func run() error {
	clear := flag.Bool("clear", false, "empty the pins in every package")
	fixture := flag.String("fixture", "", "write the pins as JSON to this file, not into the packages")
	flag.Parse()
	var pins map[string]pin
	if !*clear {
		if flag.NArg() != 1 {
			return errors.New("usage: pinhashes [-fixture file] <directory of release files>, or pinhashes -clear")
		}
		var err error
		if pins, err = read(flag.Arg(0)); err != nil {
			return err
		}
	}
	if *fixture != "" {
		b, err := json.MarshalIndent(pins, "", "  ")
		if err != nil {
			return err
		}
		return os.WriteFile(*fixture, append(b, '\n'), 0o644)
	}
	for _, t := range targets {
		if err := os.WriteFile(filepath.FromSlash(t.path), []byte(render(t, pins)), 0o644); err != nil {
			return err
		}
	}
	return nil
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "pinhashes:", err)
		os.Exit(1)
	}
}
